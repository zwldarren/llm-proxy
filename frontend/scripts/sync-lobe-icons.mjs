#!/usr/bin/env node
/**
 * Regenerate `src/utils/lobeBrands.generated.ts` from the published
 * `@lobehub/icons-static-svg` package.
 *
 * The icon resolver matches model ids and provider types against the *whole*
 * catalog the package ships instead of a hand-written table, so the catalog has
 * to be available offline: it is committed, and this script is the only thing
 * that writes it.
 *
 *   bun run icons:sync
 *
 * The script pins the icon CDN URLs the app builds to the version it recorded,
 * so a brand that is in the catalog is guaranteed to exist on the CDN.
 */
import { writeFile } from "node:fs/promises";

const PKG = "@lobehub/icons-static-svg";
const OUT = new URL("../src/utils/lobeBrands.generated.ts", import.meta.url);

/** Wordmark / lockup variants fold into their base brand. */
const TEXT_SUFFIXES = ["-text-cn", "-text-color", "-text", "-brand-color", "-brand"];
const COLOR_SUFFIX = "-color";

async function getJson(url) {
  const response = await fetch(url, { headers: { accept: "application/json" } });
  if (!response.ok) {
    throw new Error(`${url} -> HTTP ${response.status}`);
  }
  return response.json();
}

/** Latest published version, so a run never depends on a stale local pin. */
async function latestVersion() {
  const meta = await getJson(`https://registry.npmjs.org/${PKG}/latest`);
  const version = meta?.version;
  if (typeof version !== "string" || !version) {
    throw new Error(`could not read a version from the registry metadata of ${PKG}`);
  }
  return version;
}

/** File listing straight out of the CDN's package index. */
async function iconSlugs(version) {
  const listing = await getJson(
    `https://data.jsdelivr.com/v1/packages/npm/${PKG}@${version}?structure=flat`
  );
  const files = listing?.files;
  if (!Array.isArray(files)) {
    throw new Error(`unexpected jsDelivr payload for ${PKG}@${version}`);
  }
  return files
    .map((file) => file?.name)
    .filter((name) => typeof name === "string" && name.startsWith("/icons/"))
    .map((name) => name.slice("/icons/".length, -".svg".length));
}

function stripTextSuffix(slug) {
  for (const suffix of TEXT_SUFFIXES) {
    if (slug.endsWith(suffix)) {
      return slug.slice(0, -suffix.length);
    }
  }
  return slug;
}

/**
 * Split the listing into the two files the resolver needs:
 *
 * - a mono brand has `<brand>.svg` (a `currentColor` mark, themable via CSS);
 * - a colour brand has `<brand>-color.svg` (a fixed-palette mark).
 *
 * Wordmarks and lockups are dropped: a UI tile shows the mark, never the
 * wordmark, so they would only ever be matched by mistake.
 */
function splitBrands(slugs) {
  const mono = new Set();
  const color = new Set();
  for (const slug of slugs) {
    const base = stripTextSuffix(slug);
    if (base.endsWith(COLOR_SUFFIX)) {
      const brand = base.slice(0, -COLOR_SUFFIX.length);
      if (brand) color.add(brand);
    } else if (base) {
      mono.add(base);
    }
  }
  return { mono, color };
}

function renderList(name, brands) {
  const body = brands.map((brand) => `  ${JSON.stringify(brand)},`).join("\n");
  return `export const ${name}: readonly string[] = [\n${body}\n];`;
}

function renderModule(version, mono, color) {
  return `// Generated by \`scripts/sync-lobe-icons.mjs\` (\`bun run icons:sync\`). Do not edit.
//
// Source: ${PKG}@${version}
// https://github.com/lobehub/lobe-icons

/** Upstream package release this catalog was generated from. */
export const LOBE_ICONS_VERSION = ${JSON.stringify(version)};

/** Brands shipping a mono mark (\`<brand>.svg\`), matched in id order. */
${renderList("LOBE_MONO_BRANDS", mono)}

/** Brands shipping a fixed-palette mark (\`<brand>-color.svg\`). */
${renderList("LOBE_COLOR_BRANDS", color)}
`;
}

const version = await latestVersion();
const { mono, color } = splitBrands(await iconSlugs(version));

if (mono.size < 100) {
  throw new Error(`suspiciously small catalog (${mono.size} brands) — refusing to write`);
}

const sortedMono = [...mono].sort();
const sortedColor = [...color].sort();
await writeFile(OUT, renderModule(version, sortedMono, sortedColor), "utf8");

const orphans = sortedColor.filter((brand) => !mono.has(brand));
console.log(
  `lobe icons ${version}: ${sortedMono.length} brands, ${sortedColor.length} with a colour mark ` +
    `(${orphans.length} colour-only) -> src/utils/lobeBrands.generated.ts`
);
if (orphans.length) {
  console.log(`  colour-only brands: ${orphans.join(", ")}`);
}
